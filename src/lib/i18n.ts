const zhPatterns: [RegExp, (...matches: string[]) => string][] = [
  [/^Account: (.+)$/, (_, name) => `账号：${name}`],
  [/^(\d+) of (\d+)$/, (_, a, b) => `${a} / ${b}`],
  [/^(\d+) of (\d+) stacks · (\d+) relics$/, (_, a, b, c) => `${a} / ${b} 组 · 共 ${c} 个遗物`],
  [/^Filters \((\d+)\)$/, (_, count) => `筛选 (${count})`],
  [/^Add (weapon|Warframe|relic)$/, (_, kind) => `添加${zhExact[kind] ?? (kind === 'weapon' ? '武器' : kind === 'relic' ? '遗物' : kind)}`],
  [/^Edit (.+)$/, (_, name) => `编辑 ${name}`],
  [/^Import (\d+) items?$/, (_, count) => `导入 ${count} 项`],
  [/^Import (\d+) stacks?$/, (_, count) => `导入 ${count} 组`],
  [/^Reading screenshots… (\d+)%$/, (_, pct) => `正在识别截图… ${pct}%`],
  [/^Drop, paste, or choose · (\d+)\/10 images$/, (_, count) => `拖放、粘贴或选择 · ${count}/10 张图片`],
];

export function t(text: string): string {
  if (currentLanguage === 'en' || !text) return text;
  const exact = zhExact[text];
  if (exact) return exact;
  for (const [pattern, replace] of zhPatterns) {
    const match = pattern.exec(text);
    if (match) return replace(...match);
  }
  return text;
}

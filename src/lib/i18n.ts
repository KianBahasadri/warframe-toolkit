import { useSyncExternalStore } from 'react';

export type Language = 'en' | 'zh';
export const LANGUAGE_STORAGE_KEY = 'grakata.language';
export const LANGUAGES: readonly { code: Language; label: string }[] = [
  { code: 'en', label: 'English' },
  { code: 'zh', label: '简体中文' },
];

function readStoredLanguage(): Language {
  try {
    return localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'zh' ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

let currentLanguage: Language = typeof window === 'undefined' ? 'en' : readStoredLanguage();
const listeners = new Set<() => void>();

if (typeof document !== 'undefined') {
  document.documentElement.lang = currentLanguage === 'zh' ? 'zh-CN' : 'en';
}

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(next: Language): void {
  const normalized: Language = next === 'zh' ? 'zh' : 'en';
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, normalized);
  } catch {
    // Language still updates for the active session if storage is blocked.
  }
  if ( typeof document !== 'undefined') {
    document.documentElement.lang = normalized === 'zh' ? 'zh-CN' : 'en';
  }
  if (currentLanguage === normalized) return;
  currentLanguage = normalized;
  for (const listener of listeners) listener();
}

export function subscribeLanguage(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function useLanguage(): [Language, (next: Language) => void] {
  const language = useSyncExternalStore(subscribeLanguage, getLanguage, () => 'en' as Language);
  return [language, setLanguage];
}

